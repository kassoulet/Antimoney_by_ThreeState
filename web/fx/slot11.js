// 0x404010 (keys sorted by time): A = last key <= t, K0 = key before A, B = key after A, C = key after B (missing neighbours repeat the nearest, as in the loops of the original)
export function keyframe(t, tn = f(0.5)) {
  const K = KEYS, first = K[0], last = K[K.length - 1];
  let A = first, K0 = first, B = first, C = first;
  for (const k of K) if (k[0] <= t && k[0] > A[0]) A = k;
  for (const k of K) if (k[0] < A[0] && k[0] >= K0[0]) K0 = k;
  for (const k of K) if (k[0] > B[0]) B = k;
  for (const k of K) if (k[0] > A[0] && k[0] < B[0]) B = k;
  for (const k of K) if (k[0] > C[0]) C = k;
  for (const k of K) if (k[0] > B[0] && k[0] < C[0]) C = k;
  const dt = B[0] - A[0];
  if (!dt) return A.slice(1).map(f);
  const s = f((t - A[0]) / dt), s2 = f(s * s), s3 = f(s2 * s), L1 = f(s3 + s3);
  const h00 = f(f(L1 - f(s2 * 3)) + 1), h01 = f(f(s2 * 3) + f(s3 * -2)), h10 = f(f(s3 - f(s2 + s2)) + s), h11 = f(s3 - s2);
  return [1, 2, 3, 4, 5, 6].map(c => {
    const v0 = f(A[c]), v1 = f(B[c]), v2 = f(f(f(B[c]) - f(K0[c])) * tn), v3 = f(f(f(C[c]) - f(A[c])) * tn);
    return f(f(f(f(h11 * v3) + f(h10 * v2)) + f(h01 * v1)) + f(h00 * v0));
  });
}
